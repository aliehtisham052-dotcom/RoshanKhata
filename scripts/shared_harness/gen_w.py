#!/usr/bin/env python3
"""Writes the stand-in for the W / WP / WA name objects the shared module gets from Gradle (:shared:generateWordKeys).

Same rule as shared/build.gradle.kts: every <string>, <plurals> and <string-array> name in app/src/main/res/values
(strings.xml and arrays.xml), sorted, one `const val name = "name"` each, Kotlin keywords in backticks. Usage:

    python3 scripts/shared_harness/gen_w.py <out/W.kt>
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
KEYWORDS = {"as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
            "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var",
            "when", "while"}


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    res = ROOT / "app/src/main/res/values"
    text = "\n".join((res / f).read_text(encoding="utf-8") for f in ("strings.xml", "arrays.xml") if (res / f).is_file())

    def names(tag):
        return sorted(set(re.findall(r"<%s\s+name=\"([^\"]+)\"" % tag, text)))

    def block(obj, doc, items):
        lines = ["/** %s */" % doc, "object %s {" % obj]
        lines += ['    const val %s = "%s"' % ("`%s`" % n if n in KEYWORDS else n, n) for n in items]
        return "\n".join(lines) + "\n}\n\n"

    out = pathlib.Path(sys.argv[1])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// Generated by scripts/shared_harness/gen_w.py from app/src/main/res/values. Do not edit.\n"
        "package com.innovation313.roshankhata.words\n\n"
        + block("W", "Every string's name.", names("string"))
        + block("WP", "Every plural's name.", names("plurals"))
        + block("WA", "Every list's name (string-array).", names("string-array")),
        encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
