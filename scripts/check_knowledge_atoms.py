#!/usr/bin/env python3
"""Hudhud's knowledge atoms (Marhala 9, lane B, D16; 26 Nov 2026): shared/hudhud/knowledge/atoms.tsv, checked, and the table the app
ships written from it.

    python3 scripts/check_knowledge_atoms.py           # check (Strings CI, run_release_checks.sh); exit 1 on any problem
    python3 scripts/check_knowledge_atoms.py --write   # write HudhudKnowledgeAtoms.kt from atoms.tsv, then check

Fails when
  1. the header is not the loader's (KnowledgeAtom.COLUMNS), an id is malformed or repeated, or its module is not its hundreds;
  2. a title, definition, example or exception key is missing from values/strings.xml or from any of the eight other locales;
  3. a formula id is not a row of docs/formula-book.tsv;
  4. a source has no https address, its tier is not 1 to 5, the sources, addresses and tiers do not pair up, or every source of an
     atom is tier 5 (a blog or a forum never stands alone);
  5. an AI is named as a source, an address or a reviewer (an AI is never a source: plan v1, Marhala 9);
  6. the day read is not a real day (YYYY-MM-DD) or is after today;
  7. HudhudKnowledgeAtoms.kt is not exactly what this script writes from atoms.tsv (the file moved without its table).
Drift protection, not proof (lesson 125): it cannot say that a definition is TRUE to its source; a person reviews each atom and
writes their name in reviewed_by ("pending" until then, and the card says "general guidance").
"""
import csv
import datetime
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ATOMS = ROOT / "shared/hudhud/knowledge/atoms.tsv"
KT = ROOT / "shared/src/jvmSharedMain/kotlin/com/innovation313/roshankhata/data/HudhudKnowledgeAtoms.kt"
FORMULAS = ROOT / "docs/formula-book.tsv"
RES = ROOT / "app/src/main/res"
LOCALES = ["values", "values-b+ur+Latn", "values-ur", "values-sd", "values-fa", "values-ar", "values-in", "values-hi", "values-bn"]
COLUMNS = ["id", "module", "concept", "title", "definition", "example", "exception", "formula_id", "source", "source_url",
           "source_tier", "date_read", "reviewed_by"]
AI_WORDS = re.compile(r"chatgpt|openai|\bclaude\b|anthropic|gemini|\bbard\b|copilot|perplexity|deepseek|\bllm\b|ai[- ]generated|"
                      r"generated by (an )?ai|grok|mistral", re.I)


def rows():
    lines = [l for l in ATOMS.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]
    return lines[0].split("\t"), [l.split("\t") for l in lines[1:]]


def keys_of(folder):
    text = (RES / folder / "strings.xml").read_text(encoding="utf-8")
    return set(re.findall(r'<string\s+name="([^"]+)"', text))


def kt_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def render(data):
    out = [
        "// GENERATED by scripts/check_knowledge_atoms.py --write from shared/hudhud/knowledge/atoms.tsv. Do not edit: change the",
        "// TSV and run the script; Strings CI fails when this table and the TSV differ.",
        "package com.innovation313.roshankhata.data",
        "",
        "import com.innovation313.roshankhata.words.W",
        "",
        "/** The knowledge atoms the app ships ([KnowledgeAtom]): the words are the app's own strings, named here so the phone keeps them. */",
        "internal object HudhudKnowledgeAtoms {",
        "    val ALL: List<KnowledgeAtom> = listOf(",
    ]
    items = []
    for r in data:
        d = dict(zip(COLUMNS, r))

        def key(v):
            return "null" if v == "-" else "W." + v

        many = lambda v: "listOf(" + ", ".join(kt_string(x.strip()) for x in v.split(" | ")) + ")"
        formulas = "emptyList()" if d["formula_id"] == "-" else "listOf(" + ", ".join(kt_string(x.strip()) for x in d["formula_id"].split(";")) + ")"
        items.append(
            "        KnowledgeAtom(\n"
            f"            id = {kt_string(d['id'])}, module = {int(d['module'])}, concept = {kt_string(d['concept'])},\n"
            f"            title = W.{d['title']}, definition = W.{d['definition']}, example = {key(d['example'])}, exception = {key(d['exception'])},\n"
            f"            formulas = {formulas},\n"
            f"            sources = {many(d['source'])},\n"
            f"            tiers = listOf({', '.join(str(int(t)) for t in d['source_tier'].split(' | '))}), dateRead = {kt_string(d['date_read'])},\n"
            f"            reviewedBy = {kt_string(d['reviewed_by'])}\n"
            "        )"
        )
    out.append(",\n".join(items))
    out += ["    )", "}", ""]
    return "\n".join(out)


def check(head, data):
    problems = []
    if head != COLUMNS:
        problems.append("atoms.tsv: the header is not " + " / ".join(COLUMNS))
        return problems
    with open(FORMULAS, encoding="utf-8", newline="") as f:
        formula_ids = {r[0] for r in csv.reader(f, delimiter="\t")}
    locale_keys = {loc: keys_of(loc) for loc in LOCALES}
    seen = set()
    today = datetime.date.today()
    for r in data:
        if len(r) != len(COLUMNS):
            problems.append(f"atoms.tsv: {len(r)} columns in a row starting {r[0]!r}")
            continue
        d = dict(zip(COLUMNS, r))
        aid = d["id"]
        if not re.fullmatch(r"K\d{3}", aid) or aid in seen:
            problems.append(f"{aid}: malformed or repeated id")
        seen.add(aid)
        if not d["module"].isdigit() or not (1 <= int(d["module"]) <= 8) or aid[1:2] != d["module"]:
            problems.append(f"{aid}: module {d['module']!r} is not 1 to 8 or not the id's hundreds")
        for col in ("title", "definition", "example", "exception"):
            k = d[col]
            if k == "-" and col in ("example", "exception"):
                continue
            for loc, ks in locale_keys.items():
                if k not in ks:
                    problems.append(f"{aid}: {col} key {k!r} missing from {loc}/strings.xml")
        if d["formula_id"] != "-":
            for fid in d["formula_id"].split(";"):
                if fid.strip() not in formula_ids:
                    problems.append(f"{aid}: formula {fid.strip()!r} is not in docs/formula-book.tsv")
        names = [x.strip() for x in d["source"].split(" | ")]
        urls = [x.strip() for x in d["source_url"].split(" | ")]
        tiers = [x.strip() for x in d["source_tier"].split(" | ")]
        if not (len(names) == len(urls) == len(tiers)) or not names[0]:
            problems.append(f"{aid}: sources, addresses and tiers do not pair up")
        for u in urls:
            if not u.startswith("https://"):
                problems.append(f"{aid}: source address {u!r} is not https")
        good = [t for t in tiers if t in ("1", "2", "3", "4", "5")]
        if len(good) != len(tiers):
            problems.append(f"{aid}: a source tier is not 1 to 5 ({d['source_tier']!r})")
        elif all(t == "5" for t in tiers):
            problems.append(f"{aid}: every source is tier 5 (a blog or a forum never stands alone)")
        for col in ("source", "source_url", "reviewed_by"):
            if AI_WORDS.search(d[col]):
                problems.append(f"{aid}: an AI named in {col} ({d[col]!r}); an AI is never a source or a reviewer")
        try:
            day = datetime.date.fromisoformat(d["date_read"])
            if day > today:
                problems.append(f"{aid}: date read {day} is after today")
        except ValueError:
            problems.append(f"{aid}: date read {d['date_read']!r} is not YYYY-MM-DD")
        if not d["reviewed_by"].strip():
            problems.append(f"{aid}: reviewed_by is empty (write 'pending' until a person has reviewed it)")
    if not KT.exists() or KT.read_text(encoding="utf-8") != render(data):
        problems.append(f"{KT.relative_to(ROOT)} differs from what the script writes from atoms.tsv: run --write")
    return problems


def main():
    head, data = rows()
    if "--write" in sys.argv[1:]:
        KT.write_text(render(data), encoding="utf-8")
    problems = check(head, data)
    for p in problems:
        print("FAIL", p)
    pending = sum(1 for r in data if len(r) == len(COLUMNS) and r[COLUMNS.index("reviewed_by")] == "pending")
    print(f"{len(data)} atoms checked, {len(problems)} problems; {pending} still waiting for a person's review")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
