#!/usr/bin/env python3
"""The sentences HudhudSpeedOnDeviceTest times on the emulator (Marhala 2: phone speed p50/p95/p99).

The held-out set (shared/src/jvmSharedTest/resources/hudhud/heldout.tsv) is a JVM test resource and is not on the
device's classpath, so a fixed sample of it is kept as an androidTest asset: in the test APK only, never in the app
the owner and Play get. The sample is every STEP-th row of the held-out file, in its own order (so all nine languages
and every meaning are in it), written as the held-out file writes rows (`language<TAB>meaning<TAB>sentence`, with the
{NAME}/{ITEM} placeholders the test fills with its invented book). Nothing in it is new: no sentence is added, none
changed.

    python3 scripts/hudhud_speed_sample.py           # write the asset again
    python3 scripts/hudhud_speed_sample.py --check   # exit 1 when the asset is not the sample of today's held-out set
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HELDOUT = ROOT / "shared/src/jvmSharedTest/resources/hudhud/heldout.tsv"
ASSET = ROOT / "app/src/androidTest/assets/hudhud/speed_sample.tsv"
STEP = 4

HEAD = [
    "# Generated by scripts/hudhud_speed_sample.py from heldout.tsv (every %d-th row); do not edit by hand." % STEP,
    "# HudhudSpeedOnDeviceTest times Hudhud.understand over these. language<TAB>meaning<TAB>sentence.",
]


def sample():
    rows = [line for line in HELDOUT.read_text(encoding="utf-8").splitlines() if line.strip()]
    return HEAD + rows[::STEP]


def main(argv):
    want = "\n".join(sample()) + "\n"
    if "--check" in argv:
        have = ASSET.read_text(encoding="utf-8") if ASSET.exists() else ""
        if have != want:
            print("hudhud_speed_sample: %s is stale; run python3 scripts/hudhud_speed_sample.py"
                  % ASSET.relative_to(ROOT))
            return 1
        print("hudhud_speed_sample: the asset is today's sample (%d sentences)" % (len(want.splitlines()) - len(HEAD)))
        return 0
    ASSET.parent.mkdir(parents=True, exist_ok=True)
    ASSET.write_text(want, encoding="utf-8")
    print("hudhud_speed_sample: wrote %d sentences to %s" % (len(want.splitlines()) - len(HEAD), ASSET.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
