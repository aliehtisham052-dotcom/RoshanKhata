COLUMNS = ["path", "role", "languages", "rows", "bytes", "sha256", "synthetic", "native_read", "sources", "origin"]

REGISTER_COLUMNS = ["id", "source", "kind", "licence", "licence_checked", "used_for", "attribution", "status", "where",
                    "notes"]
KINDS = {"own", "ai-output", "outside"}
CHECKED = {"own", "repo", "well-established", "verify"}
STATUSES = {"used", "planned", "rejected"}


def in_scope():
    found = set()
    for pattern in SCOPE:
        for p in ROOT.glob(pattern):
            if p.is_file() and "/build/" not in p.as_posix():
                found.add(p.relative_to(ROOT).as_posix())
    return sorted(found)


def rule_for(rel):
    """The first ORIGINS rule whose glob matches [rel] (fnmatch's * crosses '/', so the order above is most particular first)."""
    for rule in ORIGINS:
        if fnmatch.fnmatchcase(rel, rule[0]):
            return rule
    return None


def data_rows(path):
    return [l for l in path.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]


_bank_langs = None


def bank_languages():
    global _bank_langs
    if _bank_langs is None:
        bank, _ = BANK.read()
        present = {lang for lang, _, _ in bank}
        _bank_langs = [l for l in LANGS if l in present]
    return _bank_langs


def languages_of(path, how):
    if how == "stem":
        stem = path.stem
        return [stem] if stem in LANGS else [f"unknown ({stem})"]
    if how == "col1":
        seen = {ALIASES.get(r.split("\t")[0], r.split("\t")[0]) for r in data_rows(path)}
        return [l for l in LANGS if l in seen] + sorted(f"unknown ({s})" for s in seen if s not in LANGS)
    if how == "bank":
        return bank_languages()
    return [how]


def native_read(langs, override):
    if override:
        return override
    known = [l for l in langs if l in LANGS]
    if not known:
        return "n/a"
    beta = [l for l in known if l in BETA]
    rest = [l for l in known if l not in BETA]
    parts = []
    if beta:
        parts.append(f"beta: {','.join(beta)} (D17, AI-reviewed only)")
    if rest:
        parts.append(f"no native sign-off recorded: {','.join(rest)}")
    return "; ".join(parts)


def build():
    """(rows as dicts, problems) for the files in scope today."""
    rows, problems = [], []
    for rel in in_scope():
        if "sealed" in rel.lower():
            problems.append(f"{rel}: named like the sealed set, which stays in the owner's folder outside the repository (D12, D18)")
        rule = rule_for(rel)
        if rule is None:
            problems.append(f"{rel}: a data file with no ORIGINS rule in scripts/hudhud_manifest.py (state its role and "
                            "origin there; write 'unknown' for what the repository cannot say)")
            continue
        _, role, how, synthetic, sources, origin, *rest = rule
        path = ROOT / rel
        b = path.read_bytes()
        try:
            b.decode("utf-8")
            binary = rel.endswith(".bin")
        except UnicodeDecodeError:
            binary = True
        langs = languages_of(path, how) if how != "n/a" else []
        rows.append({
            "path": rel, "role": role, "languages": ",".join(langs) if langs else "n/a",
            "rows": "-" if binary else str(len(data_rows(path))), "bytes": str(len(b)), "sha256": sha(b),
            "synthetic": synthetic, "native_read": native_read(langs, rest[0] if rest else None),
            "sources": sources, "origin": origin,
        })
    for rule in ORIGINS:
        if not any(fnmatch.fnmatchcase(r["path"], rule[0]) and rule_for(r["path"]) is rule for r in rows):
            problems.append(f"ORIGINS rule {rule[0]!r} matches no data file (a stale rule: remove or fix it)")
        if rule[1] not in ROLES or rule[3] not in SYNTHETIC:
            problems.append(f"ORIGINS rule {rule[0]!r}: role {rule[1]!r} or synthetic {rule[3]!r} not allowed")
    return rows, problems


def render(rows):
    head = [
        "# GENERATED by scripts/hudhud_manifest.py (plan v1, Marhala 12): every data file Hudhud is trained, tuned or tested on.",
        "# Do not edit: change ORIGINS in the script and run it; --check (Strings CI, run_release_checks.sh) fails when a file moved",
        "# without this record. Roles: train, dev (tuned while looking: not an accuracy figure), regression (rows held exactly),",
        "# pages, model, catalog. native_read: D17 calls sd, bn, fa, ar \"beta\" until a native speaker reads them. Sources are ids",
        "# of docs/hudhud-rights-register.tsv. The sealed set v2 is never listed: it stays in the owner's folder (D12, D18).",
        "\t".join(COLUMNS),
    ]
    return "\n".join(head + ["\t".join(r[c] for c in COLUMNS) for r in rows]) + "\n"


def read_tsv(path, columns):
    """(rows as dicts, problems) of a '#'-commented TSV whose first data line is the header [columns]."""
    lines = [l for l in path.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]
    if not lines or lines[0].split("\t") != columns:
        return [], [f"{path.relative_to(ROOT)}: the header is not {' / '.join(columns)}"]
    out, problems = [], []
    for n, line in enumerate(lines[1:], 2):
        cells = line.split("\t")
        if len(cells) != len(columns):
            problems.append(f"{path.relative_to(ROOT)}: data line {n} has {len(cells)} columns, not {len(columns)}")
            continue
        out.append(dict(zip(columns, cells)))
    return out, problems


def check_manifest(rows):
    problems = []
    if not MANIFEST.exists():
        return [f"{MANIFEST.relative_to(ROOT)} is missing: run python3 scripts/hudhud_manifest.py"]
    listed, bad = read_tsv(MANIFEST, COLUMNS)
    problems += bad
    by_path = {r["path"]: r for r in listed}
    now = {r["path"]: r for r in rows}
    for rel, r in now.items():
        old = by_path.get(rel)
        if old is None:
            problems.append(f"{rel}: a data file the manifest does not list")
            continue
        moved = [f"{c} {old[c]} -> {r[c]}" if c != "sha256" else f"sha256 {old[c][:12]}.. -> {r[c][:12]}.."
                 for c in ("sha256", "rows", "bytes", "languages") if old[c] != r[c]]
        if moved:
            problems.append(f"{rel}: changed without the manifest ({'; '.join(moved)})")
    for rel in by_path:
        if rel not in now:
            problems.append(f"{rel}: listed in the manifest but no longer in the repository")
    if not problems and MANIFEST.read_text(encoding="utf-8") != render(rows):
        problems.append(f"{MANIFEST.relative_to(ROOT)} differs from what the script writes (a hand edit, or ORIGINS changed)")
    return problems


def check_register(rows):
    problems, backlog = [], []
    if not REGISTER.exists():
        return [f"{REGISTER.relative_to(ROOT)} is missing"], []
    reg, bad = read_tsv(REGISTER, REGISTER_COLUMNS)
    problems += bad
    ids = [r["id"] for r in reg]
    for i in sorted({i for i in ids if ids.count(i) > 1}):
        problems.append(f"rights register: id {i} is written twice")
    for r in reg:
        where = f"rights register {r['id']}"
        if not re.fullmatch(r"RS-\d{2}", r["id"]):
            problems.append(f"{where}: an id is RS-<two digits>")
        if r["kind"] not in KINDS:
            problems.append(f"{where}: kind {r['kind']!r} not in {sorted(KINDS)}")
        if r["licence_checked"] not in CHECKED:
            problems.append(f"{where}: licence_checked {r['licence_checked']!r} not in {sorted(CHECKED)}")
        if r["status"] not in STATUSES:
            problems.append(f"{where}: status {r['status']!r} not in {sorted(STATUSES)}")
        if any(not r[c].strip() for c in REGISTER_COLUMNS):
            problems.append(f"{where}: an empty cell (write 'none' or 'unknown')")
        for item in (s.strip() for s in r["where"].split(";")):
            token = item.split(" ")[0].split("#")[0].split("::")[0]
            if "/" in token and re.search(r"\.(py|kt|kts|tsv|md|bin|xml|yml|sh)$", token) and not (ROOT / token).exists():
                problems.append(f"{where}: names {token}, which is not in the repository")
        if r["status"] == "used" and r["licence_checked"] == "verify":
            backlog.append(r["id"])
    known = set(ids)
    named = set()
    for row in rows:
        for s in row["sources"].split(";"):
            named.add(s.strip())
            if s.strip() not in known:
                problems.append(f"{row['path']}: source {s.strip()} is not a row of the rights register")
    for r in reg:
        if r["status"] == "rejected" and r["id"] in named:
            problems.append(f"rights register {r['id']} is rejected, yet the manifest names it as a source")
    return problems, backlog


def check_decision_log():
    recorded = {}
    for f in sorted((ROOT / "docs").glob("decisions-*.md")):
        for m in re.finditer(r"^\|\s*(D\d+)\s*\|", f.read_text(encoding="utf-8"), re.M):
            recorded.setdefault(m.group(1), []).append(f"docs/{f.name}")
    if not DECISION_LOG.exists():
        return [f"{DECISION_LOG.relative_to(ROOT)} is missing"]
    logged = {}
    for m in re.finditer(r"^\|\s*(D\d+)\s*\|(.*)$", DECISION_LOG.read_text(encoding="utf-8"), re.M):
        logged.setdefault(m.group(1), []).append(m.group(2))
    problems = [f"decision log: {d} is recorded in {', '.join(recorded[d])} but not in docs/decision-log.md"
                for d in sorted(set(recorded) - set(logged), key=lambda d: int(d[1:]))]
    problems += [f"decision log: {d} is in docs/decision-log.md but in no docs/decisions-*.md"
                 for d in sorted(set(logged) - set(recorded), key=lambda d: int(d[1:]))]
    problems += [f"decision log: {d} has {len(v)} rows" for d, v in logged.items() if len(v) > 1]
    for d, cells in logged.items():
        for f in recorded.get(d, []):
            if f not in cells[0]:
                problems.append(f"decision log: {d}'s row does not name {f}, where it is recorded")
    return problems


def main(argv):
    rows, problems = build()
    if "--check" not in argv:
        if problems:
            print("hudhud manifest: not written:\n  " + "\n  ".join(problems))
            return 1
        MANIFEST.write_text(render(rows), encoding="utf-8")
        print(f"hudhud manifest: wrote {len(rows)} data files to {MANIFEST.relative_to(ROOT)}")
        return 0
    problems += check_manifest(rows)
    reg_problems, backlog = check_register(rows)
    problems += reg_problems
    problems += check_decision_log()
    if problems:
        print("hudhud manifest: FAIL\n  " + "\n  ".join(problems))
        print("Regenerate with python3 scripts/hudhud_manifest.py after the change is meant (and its origin stated).")
        return 1
    if backlog:
        print(f"hudhud rights register: {len(backlog)} used source(s) whose licence a person must still verify: {', '.join(backlog)}")
    print(f"hudhud manifest OK: {len(rows)} data files listed and current; every source in the rights register; "
          f"the decision log matches docs/decisions-*.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
