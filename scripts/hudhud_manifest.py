#!/usr/bin/env python3
"""Hudhud's data manifest and the governance files' checks (plan v1, Marhala 12; 25 Nov 2026).

    python3 scripts/hudhud_manifest.py           # (re)write docs/hudhud-data-manifest.tsv from the repository
    python3 scripts/hudhud_manifest.py --check   # fail on a stale or incomplete manifest, register or decision log

The manifest has one row for every data file Hudhud is trained, tuned or tested on, found by SCOPE (not by a list somebody
remembered): the bank's sources (shared/hudhud/*.tsv, more/*.tsv), the tests' sets (the resources' hudhud/ folder of any
module), the model the app ships (the assets' hudhud/ folder of any module) and the catalog (shared/hudhud/catalog/).
Each row: path, role (train / dev / regression / pages / model / catalog), languages, rows, bytes, SHA-256, synthetic,
native read, the rights register's source ids, and the origin as the code, the file's own header and CLAUDE.md state it.
What the repository cannot say is written "unknown", never guessed. Rows, languages, bytes and hashes are computed; role,
synthetic, sources and origin come from ORIGINS below, one rule per kind of file. A file in scope that no rule matches is
refused, so a new data file is never listed without somebody stating where it came from.

--check fails when
  1. a listed file's SHA-256, rows, bytes or languages changed and the manifest was not regenerated (the data moved
     without its record), a data file appears that the manifest does not list, or a listed file is gone;
  2. a file in scope has no ORIGINS rule, or a rule matches nothing (a stale rule);
  3. a file in scope is named like the sealed set (D12, D18: it stays in the owner's folder, never here);
  4. a source id the manifest names is not a row of docs/hudhud-rights-register.tsv, or the register is malformed
     (columns, unique ids, allowed kind / licence_checked / status, a repository path it names that does not exist);
  5. docs/decision-log.md and docs/decisions-*.md disagree on which D-decisions exist.
Drift protection, not proof (lesson 125): it cannot say that an origin or a licence is TRUE; a person reads those.
Register rows whose licence is still "verify" are printed as the honest backlog and do not fail.

The SHA-256 helper is hudhud_model_card.py's own `sha` (one helper, not two). Nothing outside the repository is read.
"""
